import {test,expect} from '@playwright/test';

test('registration through manual application history against real API and PostgreSQL',async({page})=>{
  test.skip(process.env.JOBPULSE_LIVE_API!=='true','Run scripts/run-full-stack-e2e.sh; requires isolated PostgreSQL and an Ollama fixture');
  page.on('dialog',dialog=>dialog.accept());
  const username=`browser_${Date.now()}`;
  await page.goto('/');
  await page.getByRole('button',{name:'Register',exact:true}).click();
  await page.getByPlaceholder('Username').fill(username);
  await page.getByPlaceholder('Password').fill('browser-password-123');
  await page.getByPlaceholder('Email').fill(`${username}@example.com`);
  await page.getByRole('button',{name:'Register',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Login',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Login',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Jobs',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Resumes',exact:true}).click();
  const original='Senior Quality Engineer with Java and Selenium\nExample Employer, 2020-2025\nBuilt JUnit tests for Spring Boot services.';
  await page.locator('input[type=file]').setInputFiles({name:'browser-cv.txt',mimeType:'text/plain',buffer:Buffer.from(original)});
  await page.getByRole('button',{name:'Upload Resume',exact:true}).click();
  await expect(page.getByText('browser-cv.txt')).toBeVisible();
  await page.getByRole('button',{name:'Jobs',exact:true}).click();
  await page.getByRole('button',{name:'Paste a job description'}).click();
  await page.getByPlaceholder('Job title',{exact:true}).fill('Senior Quality Engineer');
  await page.getByPlaceholder('Employer',{exact:true}).fill('E2E fixture employer');
  await page.getByPlaceholder('Location',{exact:true}).fill('Toronto');
  await page.getByPlaceholder('Paste the full job description').fill('Senior Quality Engineer using Java, Selenium, JUnit and Spring Boot. This is an explicit test fixture, not a live vacancy.');
  await page.getByRole('button',{name:'Save job for matching'}).click();
  await expect(page.getByText('Manually entered — unverified')).toBeVisible();
  await page.getByRole('button',{name:'Matches',exact:true}).click();
  await page.getByRole('button',{name:'Generate truthful tailored draft'}).click();
  await expect(page.getByRole('textbox',{name:'Edit tailored resume'})).toHaveValue(new RegExp('COMPLETE ORIGINAL RESUME'));
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Save new version'}).click();
  await expect(page.getByRole('button',{name:/Open version #/})).toBeVisible();
  await page.getByRole('button',{name:'Record completed manual application'}).click();
  await expect(page.getByRole('status').filter({hasText:'Recorded as user-reported'})).toBeVisible();
  await page.getByRole('button',{name:'Applications',exact:true}).click();
  await expect(page.getByRole('combobox',{name:'Update status for Senior Quality Engineer'})).toHaveValue('USER_REPORTED_SUBMITTED');
  await page.getByRole('combobox',{name:'Update status for Senior Quality Engineer'}).selectOption('USER_REPORTED_INTERVIEW');
  await expect(page.getByRole('combobox',{name:'Update status for Senior Quality Engineer'})).toHaveValue('USER_REPORTED_INTERVIEW');
  await page.getByRole('button',{name:'Resumes',exact:true}).click();
  await page.getByRole('button',{name:'Preview / edit text'}).click();
  await expect(page.getByRole('textbox',{name:'Resume text'})).toHaveValue(original);
  const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download original'}).click();
  expect((await download).suggestedFilename()).toBe('browser-cv.txt');
  await page.getByRole('button',{name:'Logout',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Login',exact:true})).toBeVisible();
});
